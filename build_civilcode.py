def write_data() -> list:
    data = [{"en": q, "zh": a, "group": g} for g, q, a in CARDS]
    DATA_OUT.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    from collections import Counter
    for g, n in Counter(e["group"] for e in data).items():
        print(f"  {g}: {n}")
    print(f"total: {len(data)} cards")
    return data


def build_web(data: list) -> None:
    tpl = (BASE / "template.html").read_text(encoding="utf-8")
    compact = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    html = (tpl.replace("__DATA__", compact)
               .replace("英语词汇卡", TITLE)
               .replace("看英文想中文", HINT)
               .replace("vc_known", STORE_KNOWN)
               .replace("vc_wrong", STORE_WRONG)
               .replace("想一想中文意思，点击卡片查看", "先在脑中回忆法条要点，点击卡片查看")
               .replace("认识 →", "答对 →")
               .replace("不认识 ←", "答错 ←"))
    assert "__DATA__" not in html
    WEB_OUT.parent.mkdir(exist_ok=True)
    WEB_OUT.write_text(html, encoding="utf-8")
    print(f"civilcode/index.html written: {len(html) / 1024:.1f} KB")


def build_apkg(data: list) -> None:
    deck = genanki.Deck(DECK_ID, "中华人民共和国民法典背诵（高频考点）")
    for e in data:
        deck.add_note(genanki.Note(
            model=law_model,
            fields=[e["en"], e["zh"], e["group"]],
            tags=[e["group"].split("、")[0].replace("·", "")[:6]],
            guid=genanki.guid_for("civil::" + e["group"] + "::" + e["en"]),
        ))
    genanki.Package(deck).write_to_file(APKG_OUT)
    print(f"{APKG_OUT.name}: {len(data)} notes, {APKG_OUT.stat().st_size / 1024:.1f} KB")


if __name__ == "__main__":
    d = write_data()
    build_web(d)
    build_apkg(d)
